USE DATABASE LINKEDIN;
USE SCHEMA BRONZE;

-- COMPANIES
CREATE TABLE IF NOT EXISTS LINKEDIN.BRONZE.COMPANIES (data VARIANT);
COPY INTO LINKEDIN.BRONZE.COMPANIES
FROM @linkedin_stage/companies.json
FILE_FORMAT = (FORMAT_NAME = 'LINKEDIN.BRONZE.json_format');
SELECT COUNT(*) FROM LINKEDIN.BRONZE.COMPANIES;

